        "   - The yield curve fit is **extremely sensitive** to the calibration methodology. In OLS and MLE, calibration is performed purely on the time series of the short rate under the physical measure $\\mathbb{P}$. These methods ignore the market price of risk $\\lambda$, resulting in parameter estimates (especially a very high physical long-run mean $\\theta \\approx 6.6\\%$) that systematically pull predicted yields upward for longer tenors, leading to unacceptable out-of-sample $R^2$ performance (e.g. OLS R2 of $-2.2 \\times 10^{24}$ due to negative speed of mean reversion, and MLE R2 of $0.78$ with severe negative fit for long tenors).\n",
